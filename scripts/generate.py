#!/usr/bin/env python3
"""Generates plugins/no-cows/ from the no-cows MCP kit, so the plugin can never drift from the server.

    python3 scripts/generate.py --source <no-cows checkout>/web/mcp-kit          write
    python3 scripts/generate.py --source https://no-cows.com/mcp-kit --check     exit 1 if stale (CI)
    python3 scripts/generate.py --source ... --zip dist/no-cows.zip              also zip the plugin

Inputs (read-only): <source>/catalog/tools.json (generated from the server's tool table, checked by
no-cows CI) and <source>/skill/no-cows/SKILL.md (the companion skill, checked against that catalog by
no-cows CI). Output: plugins/no-cows/{.claude-plugin/plugin.json,.mcp.json,skills/no-cows/**}.
Standard library only.
"""
import json
import os
import sys
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "plugins", "no-cows")
GENERATED = "GENERATED by scripts/generate.py from the no-cows MCP kit. Do not edit."


def arg(name):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else None


def read(source, rel):
    if source.startswith("https://"):
        with urllib.request.urlopen(source.rstrip("/") + "/" + rel, timeout=30) as r:
            return r.read().decode()
    with open(os.path.join(source, rel)) as f:
        return f.read()


def build(source):
    cat = json.loads(read(source, "catalog/tools.json"))
    skill = read(source, "skill/no-cows/SKILL.md")
    if not skill.startswith("---\nname: no-cows"):
        sys.exit("generate: the skill does not start with name: no-cows")
    rows = ["<!-- " + GENERATED + " -->", "# no-cows tool catalog", "",
            f"{cat['toolCount']} tools on `{cat['server']}` (catalog `{cat['catalogHash']}`). "
            "The connected server's own tool list always wins over this file.", "",
            "| Tool | Area | Access | Two-phase | What it does |", "| --- | --- | --- | --- | --- |"]
    for t in cat["tools"]:
        rows.append(f"| `{t['name']}` | {t['area']} | {t['access']} | {'yes' if t['twoPhase'] else ''} | "
                    + t["description"].replace("|", "\\|") + " |")
    plugin = {"name": "no-cows", "version": f"1.0.0+{cat['catalogHash']}",
              "description": "The no-cows board in Claude: what is next, cards, goals, the Story, Jev's lessons, filing "
                             "items and working cards end to end, through the no-cows MCP connector. Your admin installs "
                             "it once; everyone has it.",
              "author": {"name": "Guten Group", "url": "https://no-cows.com"}, "homepage": "https://no-cows.com",
              "repository": "https://git.no-cows.com/guten-group/no-cows-claude-plugin", "license": "MIT",
              "keywords": ["no-cows", "board", "forgejo", "mcp", "agents"]}
    return {
        ".claude-plugin/plugin.json": json.dumps(plugin, indent=2) + "\n",
        ".mcp.json": json.dumps({"mcpServers": {"no-cows": {"type": "http", "url": cat["server"]}}}, indent=2) + "\n",
        "skills/no-cows/SKILL.md": skill,
        "skills/no-cows/references/tool-catalog.md": "\n".join(rows) + "\n",
        "README.md": f"<!-- {GENERATED} -->\n# no-cows plugin\n\nThe no-cows connector (`{cat['server']}`) and the no-cows skill. "
                     "Each person signs in to no-cows once, the first time Claude uses it.\n",
    }


def main():
    source = arg("--source")
    if not source:
        sys.exit("generate: --source <no-cows>/web/mcp-kit or https://no-cows.com/mcp-kit is required")
    files = build(source)
    if "--check" in sys.argv:
        stale = []
        for rel, text in files.items():
            p = os.path.join(OUT, rel)
            if not os.path.exists(p) or open(p).read() != text:
                stale.append(rel)
        have = {os.path.relpath(os.path.join(d, f), OUT) for d, _, fs in os.walk(OUT) for f in fs}
        stale += sorted(f"extra: {x}" for x in have - set(files))
        if stale:
            sys.exit("generate: plugins/no-cows is stale: " + ", ".join(stale) + ". Run scripts/generate.py and commit.")
        print("plugin current")
        return
    for rel, text in files.items():
        p = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(text)
    if arg("--zip"):
        os.makedirs(os.path.dirname(os.path.abspath(arg("--zip"))), exist_ok=True)
        with zipfile.ZipFile(arg("--zip"), "w", zipfile.ZIP_DEFLATED) as z:
            for rel in sorted(files):
                z.write(os.path.join(OUT, rel), rel)
    print("wrote plugins/no-cows")


if __name__ == "__main__":
    main()
